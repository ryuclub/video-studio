/**
 * 老石 · 开场卡（2026-09-06）
 *
 * 片子一开口，**封面上那两行字弹进画面**，停两秒多，淡掉。
 *
 * ## ⚠ 它是**替掉**句1 的字幕，不是叠在上面
 *
 * 这是这个效果能成立的唯一走法，理由是硬的：
 *
 * - 句1 的字幕本来就占满 y300–560，说的又是**同一句话**
 *   （01-A：封面主标「不是最好的」五个字，逐字出现在句1 的字幕里）。
 *   叠上去等于同一句话在一屏上写两遍。
 * - 出片方案九条第 3 条「一句只准动一样」，而开场**已经有「人走进来」这个事件**了
 *   （第二稿为了这条撤掉过开场的拉镜头）。**一换一，事件数净增为零**，这才过得去。
 *
 * 所以卡就长在**句1 让出来的字幕带里**，字号和配色跟封面 1:1
 * （主标 108px 两行纯白 —— 2026-09-08 起跟封面一起改的）。观众刚在信息流里点了那张封面，
 * 点进来第一眼是**那行字自己飞进来了** —— 这个连贯感比「全息」本身值钱。
 *
 * ## 时间按句1 的百分比算，不写死秒数
 *
 * ⚠ **配音迟早要换成本人的**（现在是 Edge 占位音），一换时间轴全变。
 * 写死 0.35/2.6/0.4 那天就全错了，而且**不报错**。
 *
 *   等 9%  → 让「人走进来」先成立，别第一帧就弹
 *   入 6%  → 竖向裂开 ＋ 从右侧滑进来
 *   持 65%
 *   出 10% → 淡出
 *   留 10% → 空场一拍再进句2
 *
 * ## 颜色照「70% 恒定 / 30% 每期切」那条分
 *
 * | | 色 | 为什么 |
 * |---|---|---|
 * | 字 | **当期类型色 ＋ 白**（`色系.mjs`） | 跟封面、跟片里的标色是同一个 |
 * | 左侧竖条 | **新闻红** | 照抄封面的栏目色条，这是频道身份 |
 * | 括号／扫描线 | **舞台灯带青 `#6ec6ff`** | 跟脚下那圈 LED 同色，读成同一套演播室的光 |
 *
 * ## ⚠ 两个静默失效
 *
 * - **`\blur` 要 libass 支持**。不支持的话**不报错，只是不糊** ——
 *   跟「ass 滤镜找不到字体自己换一个」是同一类。先出静帧看，别直接合片。
 * - **副标那行的下沿离他头顶只有 54px**（副标行底 546、头顶 600），
 *   而他走路时身体有 6px 上下颠。动字号或者动 `_机位.全身` 都要回来核这一处。
 */

/** 卡的几何和节拍。**改这儿之前先看上面那条 54px 的余量** */
export const 卡 = {
  盒: { x1: 60, y1: 285, x2: 1020, y2: 560 },
  // **投影面**：一块半透明的深蓝。第一版没有它，字压在办公室那扇亮窗上读不清，
  // 只好把描边加到 7px —— 那是"印刷体"的语言，怎么看都是一张封面贴图，不是投影。
  // 有了面就反过来了：描边降到 3、辉光露得出来，而**面本身就是"这是投出来的"那个信号**
  底: { 色: '#071A2B', 透: '&H58&' },
  条: { w: 14, 色: '#E5402C' },          // 左侧栏目色条，照抄封面
  框: '#6ec6ff',                          // 括号和扫描线，跟舞台灯带同色
  主: { x: 96, y: 300, 号: 108 },
  副: { x: 96, y: 436, 号: 92 },
  节: { 等: 0.09, 入: 0.06, 持: 0.65, 出: 0.10 },
  括号臂: 54, 括号粗: 5,
  扫描间距: 14, 扫描粗: 2, 扫描透: '&HD0&',
  描边: 3,
  辉光: { 糊: 8, 透: '&H28&' },
};

const cs = (t) => {
  const h = Math.floor(t / 3600), m = Math.floor((t % 3600) / 60), s = t % 60;
  return `${h}:${String(m).padStart(2, '0')}:${s.toFixed(2).padStart(5, '0')}`;
};
const esc = (t) => String(t).replace(/\\/g, '\\\\').replace(/\{/g, '(').replace(/\}/g, ')');
const ms = (x) => Math.round(x * 1000);

/** ASS 的画图是 `\p1` 模式，坐标跟着 `\pos` 走 —— 用 `\an7\pos(0,0)` 就等于屏幕坐标 */
const 矩 = (x, y, w, h) => `m ${x} ${y} l ${x + w} ${y} l ${x + w} ${y + h} l ${x} ${y + h} `;
/** 一个直角括号：横臂 ＋ 竖臂。sx/sy 是往哪个方向长（±1） */
const 括号 = (x, y, sx, sy, 臂, 粗) =>
  矩(sx > 0 ? x : x - 臂, sy > 0 ? y : y - 粗, 臂, 粗) +
  矩(sx > 0 ? x : x - 粗, sy > 0 ? y : y - 臂, 粗, 臂);

/**
 * 生成开场卡的 ASS 事件。
 *
 * @param seg   句1 的 { start, end }
 * @param 封面  封面.json（主标 / 重点行 / 副标）
 * @param 系    取色系() 的结果
 * @param opt   { FONT, ass色 }
 * @returns null（不该出卡）或 { 事件, 样式, 起, 止 }
 */
export function 开场卡(seg, 封面, 系, { FONT, ass色 }) {
  const 主标 = 封面?.主标, 副标 = 封面?.副标 || '';
  if (!Array.isArray(主标) || !主标.length) return null;

  const d = seg.end - seg.start;
  const 等 = d * 卡.节.等, 入 = d * 卡.节.入, 持 = d * 卡.节.持, 出 = d * 卡.节.出;
  const t0 = seg.start + 等;                 // 装饰层起
  const t文 = t0 + 入 * 0.45;                // 字比框晚半拍 —— 先有光，再有字
  const t3 = t0 + 入 + 持 + 出;              // 全部收干净
  const { x1, y1, x2, y2 } = 卡.盒;

  const 白 = '&H00FFFFFF&', 副色 = ass色(系.副);   // 2026-09-08：主标全白，不再用类型重音色
  const 框色 = ass色(卡.框), 条色 = ass色(卡.条.色), 底色 = ass色(卡.底.色);

  /** 一行字：底下一层辉光，上面一层实心。**跟字幕的双层描边是同一个手法** */
  const 行 = (文, 位, 号, 主色) => {
    const 高 = Math.round(号 * 1.2);
    const yc = 位.y + Math.round(高 / 2);
    // 竖向裂开：从一条 8px 的光缝长到整行高
    const 裂 = `\\clip(${x1},${yc - 4},${x2},${yc + 4})` +
      `\\t(0,${ms(入)},\\clip(${x1},${位.y - 10},${x2},${位.y + 高}))`;
    // 从右边滑进来一点。⚠ 有 \move 就不能再有 \pos
    const 滑 = `\\move(${位.x + 56},${位.y},${位.x},${位.y},0,${ms(入)})`;
    const 头 = `{\\an7${滑}\\fs${号}\\shad0${裂}\\fad(0,${ms(出)})`;
    // 2026-09-08：全字纯白，不再有「重点段上类型色」那套 —— 封面同日改的，两边要一致
    const 身 = `{\\1c${主色}}` + esc(文);
    return [
      // 辉光层。⚠ \blur 不被支持的话不报错、只是不糊 —— 先出静帧看
      `Dialogue: 14,${cs(t文)},${cs(t3)},卡,,0,0,0,,${头}\\bord0` +
        `\\blur${卡.辉光.糊}\\1c${主色}\\alpha${卡.辉光.透}}` + esc(文),
      // ⚠ 描边只有 3px，**能这么细是因为底下有那块投影面**。哪天把面撤了，
      // 字压在亮背景上就糊了 —— 这两个数是一起的
      `Dialogue: 15,${cs(t文)},${cs(t3)},卡,,0,0,0,,${头}\\bord${卡.描边}` +
        `\\3c&H1A0E06&\\1c${主色}}${身}`,
    ];
  };

  /**
   * ⚠ **2026-09-08：`主标` 的含义变成「几行」了**（原来是「一行里的几段」）。
   * 这儿原本是 `段.join('')` 拼成一行 —— 语义改了之后那样会把两行连成一串。
   * 现在**逐行堆叠、全字纯白**，跟封面一致（封面那边同日改的，见 cover.mjs）。
   *
   * 行距 124：主标两行正好占掉原来「主标 ＋ 副标」那两个槽位
   * （line1 y300、line2 y424，底 554，盒底 560）—— 盒子的几何一点不用动。
   */
  const 行距 = 124;
  const 主行数 = 主标.length;
  const 副y = 卡.主.y + 主行数 * 行距;
  // ⚠ 头顶 600 那条余量是硬的（见文件头「54px」那条）。副标要是把版面顶出去，
  // **当场停** —— 别静默压到人脸上
  if (副标 && 副y + Math.round(卡.副.号 * 1.2) > 566) {
    throw new Error(
      `开场卡放不下：主标 ${主行数} 行 ＋ 副标，底会到 ${副y + Math.round(卡.副.号 * 1.2)}，` +
      '超过 566（头顶 600 要留余量）。2026-09-08 起副标默认不写，删掉它，或者主标减到一行',
    );
  }

  // 装饰层：左侧色条 ＋ 四角括号 ＋ 扫描线。整块从左往右扫出来
  const 扫 = [];
  for (let y = y1 + 8; y < y2 - 8; y += 卡.扫描间距)
    扫.push(矩(x1 + 卡.条.w + 10, y, x2 - x1 - 卡.条.w - 20, 卡.扫描粗));
  const 角 = 卡.括号臂, 粗 = 卡.括号粗;
  const 框图 = 括号(x1 + 卡.条.w + 10, y1, 1, 1, 角, 粗) + 括号(x2, y1, -1, 1, 角, 粗) +
    括号(x1 + 卡.条.w + 10, y2, 1, -1, 角, 粗) + 括号(x2, y2, -1, -1, 角, 粗);
  const 扫出 = `\\clip(${x1},${y1},${x1 + 6},${y2})\\t(0,${ms(入)},\\clip(${x1},${y1},${x2},${y2}))`;
  // ⚠ 括号**不在这儿闭** —— `\p1` 得挨着 `}`，颜色由调用方补在中间。写成
  // `…\p1}` 再往后接 `\1c…` 的话，那串 tag 就跑到括号外面、被当成文字画出来
  const 装饰头 = `{\\an7\\pos(0,0)\\bord0\\shad0${扫出}\\fad(0,${ms(出)})`;

  const 事件 = [
    // 投影面压在最底下 —— 有了它字才敢只描 3px 边
    `Dialogue: 10,${cs(t0)},${cs(t3)},卡,,0,0,0,,${装饰头}\\1c${底色}\\alpha${卡.底.透}\\p1}` +
      矩(x1, y1, x2 - x1, y2 - y1),
    // 扫描线压在面上、字下面
    `Dialogue: 11,${cs(t0)},${cs(t3)},卡,,0,0,0,,${装饰头}\\1c${框色}\\alpha${卡.扫描透}\\p1}${扫.join('')}`,
    `Dialogue: 12,${cs(t0)},${cs(t3)},卡,,0,0,0,,${装饰头}\\1c${框色}\\alpha&H30&\\p1}${框图}`,
    `Dialogue: 13,${cs(t0)},${cs(t3)},卡,,0,0,0,,${装饰头}\\1c${条色}\\p1}` +
      矩(x1, y1 + 7, 卡.条.w, y2 - y1 - 14),
    // 主标逐行堆叠，全字纯白（跟封面一致）
    ...主标.flatMap((行文, i) =>
      行(行文, { x: 卡.主.x, y: 卡.主.y + i * 行距 }, 卡.主.号, 白, null)),
  ];
  if (副标) 事件.push(...行(副标, { x: 卡.副.x, y: 副y }, 卡.副.号, 副色, null));

  const 样式 = `Style: 卡,${FONT},${卡.主.号},${白},${白},&H00000000,&H00000000,` +
    `1,0,0,0,100,100,0,0,1,0,0,7,0,0,0,1`;

  return { 事件, 样式, 起: t0, 止: t3 };
}
