// ── 说书节拍表：把「这一句怎么演」变成一个标签 ────────────────────────
//
// A/B 试听定下来走 B（手工调过的节奏）。但 B 那八句的数值如果直接抄进 165 段，
// 就会散落成 165 处硬编码——以后发现「扣子停 2.2 秒太长」，得改 30 个地方。
//
// 所以把 B 的调法抽成**命名节拍**：标注稿件时只写标签（悬 / 贴近 / 揭底…），
// 数值集中在这张表里。要调整就改这一处，全片跟着变。
//
// 这跟 pace.ts 是两层：
//   · pace 定的是**整片的基础节奏**（句内 / 句间 / 换镜三层停顿）
//   · beat 定的是**这一句相对基础节奏的偏移**（这句要不要压低、要不要吊住）
//
// 数值全部来自幕二那段 A/B 实测，不是拍脑袋。
//
// ── 停顿全面收紧（第二轮试听的结论）──
//
// 第一版的停顿给到 1.2~2.2s，反馈是"停多了，不舒服"。根因不是长度本身，
// 而是**我们插的是绝对静音**：实测 −227dB，现实里不存在这种东西。
// 真人停两秒，听众听得到换气和现场；广播里的长停底下永远垫着环境声。
// 没有任何底噪时，停顿越长越像"卡带"，不像"酝酿"。
//
// 所以**所有停顿压到 1.0 秒以内**，最长的「收」也只有 1.0。
// 音量和语速的差异**原样保留** —— 那两样不依赖长停顿工作，
// 而 15 分钟全程一个音量一个语速是另一种失败：单调。
//
// 如果以后给全片垫上房间底噪（−48dB 粉噪），这张表的停顿可以整体放回去。

export interface ShuoshuBeat {
  /** 念法预设名，见 cast.ts 的 DELIVERIES */
  delivery: string;
  /** 这句之后留白（秒） */
  pause: number;
  /** 音量倍率，1 是常态 */
  gain: number;
  desc: string;
}

