/**
 * 打印。**⚠ 三支 check 其实都没调它** —— 它们各自 import `checkDiction` 自己打印，
 * 所以这个函数长期是死代码，连带它末尾那句「剩下五样只有人能看」**从来没印出来过**。
 * 2026-08-26 发现：这正是「用语太书面」反复失守的第三个机制 ——
 * **清单写了，但没有任何一个时刻会出现在眼前。**
 * 现在把 `必答清单` 单独导出，三支各自在收尾处印一次。
 */
export function printDiction(issues: DictionIssue[]): { err: number; warn: number } {
  const err = issues.filter((x) => x.level === 'error');
  const warn = issues.filter((x) => x.level === 'warn');
  if (!issues.length) {
    console.log('  ✓ 用语规范：机器查得了的八项都过了');
  } else {
    for (const i of err) console.log(`  ✗ [${i.rule}] ${i.msg}`);
    for (const i of warn) console.log(`  ⚠ [${i.rule}] ${i.msg}`);
  }
  console.log(必答清单);
  return { err: err.length, warn: warn.length };
}
