/** 写数字也行，省得记名字 */
const 别名 = { 一: '内幕', 二: '博弈', 三: '认知', 1: '内幕', 2: '博弈', 3: '认知' };

/**
 * 取一期的色系。**类型是每期必须自己写的**，不给默认值猜 ——
 * 猜错了整张封面的颜色都在说错话，而这是个一眼能定的事。
 */
export function 取色系(类型, 出处 = '动作表.json / 封面.json') {
  const k = 别名[类型] || 类型;
  const s = 色系[k];
  if (s) return { 类型: k, ...s };
  const 可选 = Object.entries(色系).map(([n, v]) => `${n}（${v.名}）`).join('　');
  console.error(`${出处} 里的「类型」写的是「${类型 ?? '（没写）'}」，认不出来`);
  console.error(`  只能是：${可选}`);
  console.error('  也可以写 一／二／三');
  process.exit(1);
}

/** `#RRGGBB` → ASS 的 `&HBBGGRR&`。⚠ 写反了不报错，只是颜色不对 */
export const ass色 = (hex) => {
  const m = /^#([0-9a-fA-F]{6})$/.exec(hex);
  if (!m) throw new Error(`不是 #RRGGBB：${hex}`);
  const [r, g, b] = [0, 2, 4].map((i) => m[1].slice(i, i + 2).toUpperCase());
  return `&H${b}${g}${r}&`;
};
