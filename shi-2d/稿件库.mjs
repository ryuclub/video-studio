/**
 * 老石 · 稿件库读取（`老石频道方案.md` §四 八条稿）
 *
 * **稿子的正本是那份方案，这儿只是把它读出来。** 页面、动作表、出片脚本一律不存第二份 ——
 * 抄一份出来，改了方案忘了改副本是迟早的事，而且**不报错**。
 *
 * ## 为什么 build 要读它：标色跟着「大字」走
 *
 * 2026-09-07 用户定的：**字幕的标色不按「这个词算不算信息」判断，就跟稿子里的大字走。**
 * 字幕里有跟大字对得上的就标，没有就不标。
 *
 * 这比原来那套「数／名／令」强的地方是**判据可以闸**：原来「这个词算不算信息」
 * 是编辑判断，写规范的时候就承认了闸不住；现在大字是稿子里写死的，一查就知道。
 *
 * 顺带把「哪个词该突出」这个决定**从排片挪回了写稿** —— 在稿子里定一次，
 * 而不是每次排镜头的时候重新想一遍。
 *
 * ⚠ **匹配是「大字 ∩ 台词」的公共部分**，不是相等。八条稿 16 处大字里**一半不是台词的原样子串**，
 * 而且六处是同一个毛病：大字用阿拉伯数字、台词用汉字数字（「30 套」对「三十套」）。
 * 那是**故意的分工** —— 大字和封面要冲击力，台词是说出来的话。所以：
 *   大字「上一位什么时候搬走的」 ＋ 台词「…这套房上一位租客什么时候搬走的」
 *     → 可以标「什么时候搬走的」（两边都有）
 *   大字「30 套」 ＋ 台词「看了三十套还没定的」
 *     → 公共部分只有「套」，太短，**这一处就不标**。别改稿去迁就。
 */
import fs from 'node:fs';
import path from 'node:path';

/** 标最短几个字。公共部分只剩一个「套」「年」那种，标了等于没标 */
export const 最短标 = 2;

/**
 * 读 §四，返回 { '01-A': { 标题, 封面, 拍: [{ 台词, 大字 }] }, … }
 */
export function 读稿件库(方案 = new URL('./老石频道方案.md', import.meta.url)) {
  const md = fs.readFileSync(方案, 'utf8');
  const a = md.indexOf('## 四、八条稿');
  const b = md.indexOf('## 五、出片流程');
  if (a < 0 || b < 0) throw new Error('老石频道方案.md 里找不到「## 四、八条稿」那一节');
  const 出 = {};
  for (const c of md.slice(a, b).split(/\n### /).slice(1)) {
    const 头 = c.split('\n')[0];                       // 「01-A ｜揭穿｜中介带你看的第一套房」
    const 号 = 头.split('｜')[0].trim();
    出[号] = {
      标题: (/\*\*标题\*\*\s+(.+)/.exec(c) || [])[1]?.trim() || '',
      封面: (/\*\*封面\*\*\s+(.+)/.exec(c) || [])[1]?.replace(/`/g, '').trim() || '',
      拍: c.split(/\n\[/).slice(1).map((b2) => ({
        台词: (/台词\s+(.+)/.exec(b2) || [])[1]?.trim() || '',
        大字: (/大字\s+(.+)/.exec(b2) || [])[1]?.trim() || null,
      })),
    };
  }
  return 出;
}

/** 这一期所有的大字（按出现顺序） */
export const 大字表 = (条) => 条.拍.map((b) => b.大字).filter(Boolean);

/**
 * `词` 是不是「某个大字和它自己的台词的公共部分」。
 * 返回命中的那个大字，没命中返回 null。
 */
export function 认大字(词, 条) {
  if ([...词].length < 最短标) return null;
  for (const b of 条.拍) {
    if (!b.大字) continue;
    if (b.大字.includes(词)) return b.大字;                 // 词 ⊆ 大字
    if (词.includes(b.大字.replace(/\s/g, ''))) return b.大字; // 大字（去空格）⊆ 词
  }
  return null;
}
