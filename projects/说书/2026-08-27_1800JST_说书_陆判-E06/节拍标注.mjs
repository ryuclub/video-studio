// ── ① 规则层 ─────────────────────────────────────────────────────────
const pickOf = (text) => {
  for (const [k, v] of Object.entries(PICK)) if (text.startsWith(k)) return v;
  return null;
};

for (let i = 0; i < L.length; i++) {
  const l = L[i];
  const hit = pickOf(l.text);
  if (hit) { l.beat = hit; continue; }
  const isLast = i === L.length - 1 || L[i + 1].act !== l.act;
  if (isLast) { l.beat = '落定'; continue; }

  if (l.who !== '说书人') {
    // 对白：短的断言平着揭，长的自陈拉近
    l.beat = len(l.text) <= 12 ? '揭底' : '贴近';
    continue;
  }
  // 旁白
  const n = len(l.text);
  const prev = i > 0 ? L[i - 1] : null;
  const next = L[i + 1];
  // 段落收尾 → 落定。判据是**下一句换了场景**（那天 / 第二天 / 后来 / 从那以后…）——
  // 稿子改成一句一条之后，「段」这个单位在文本里没有标记了，只能靠转场词反推
  const SHIFT = /^(那天|那年|第二天|第五天|后来|从那|这以后|再往后|隔了|一年|又一年|过了|天亮|头七|出殡|上任|发榜)/;
  if (next && next.act === l.act && SHIFT.test(next.text) && n <= 20) l.beat = '落定';
  else if (n <= 8 && prev && len(prev.text) >= 14) l.beat = '顿';
  else if (/^(然后|接着|一路|随着|扭身|往上|弯下|风一|走到)/.test(l.text)) l.beat = '提速';
  else l.beat = '常规';
}

// ── 打散：同一 beat 不许连续超过五句（规范 §五）────────────────────────
//
// 规则层最容易堆出一长串「常规」。超了就把第六句改掉 ——
// 短的给「顿」，长的给「贴近」。**这是保底，不是设计**。
let run = 1;
for (let i = 1; i < L.length; i++) {
  if (L[i].beat === L[i - 1].beat) run++;
  else { run = 1; continue; }
  if (run > 5) {
    if (PICK[Object.keys(PICK).find((k) => L[i].text.startsWith(k))]) continue;
    L[i].beat = len(L[i].text) <= 12 ? '顿' : '贴近';
    run = 1;
  }
}

// ── 揭底 ≤12%：超了就把最长的那几条降成贴近 ───────────────────────────
const REVEAL_MAX = Math.floor(L.length * 0.12);
let reveals = L.filter((l) => l.beat === '揭底');
if (reveals.length > REVEAL_MAX) {
  reveals.sort((a, b) => len(b.text) - len(a.text));
  for (const l of reveals.slice(0, reveals.length - REVEAL_MAX)) l.beat = '贴近';
}

// ── 落盘：前缀键的表，补稿之后能重贴 ──────────────────────────────────
const uniq = (text) => {
  for (let n = 1; n <= text.length; n++) {
    const k = text.slice(0, n);
    if (L.filter((x) => x.text.startsWith(k)).length === 1) return k;
  }
  return null;
};
const table = {};
let noAnchor = 0;
for (const l of L) {
  const k = uniq(l.text);
  if (k) table[k] = l.beat;
  else noAnchor++;
}
j.annotated = true;
