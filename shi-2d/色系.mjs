/**
 * 老石 · 话题类型 → 辅助色（2026-09-06 定）
 *
 * **70% 恒定，30% 每期切。** 恒定的那 70% 是频道身份：深藏青底、得意黑、
 * 新闻红的角标块和左侧色条、人物、版式。每期切的 30% 只有三样：
 *
 *   1. **主标重点段的字色**（封面）
 *   2. **副标的字色**（封面，取重点色的浅一档）
 *   3. **背景的光晕／光斑／数据线条**（封面）
 *
 * 外加片子里的**字幕标色** —— 它必须跟封面同一个色（见下面「为什么片子也要跟」）。
 *
 * ## 三种类型
 *
 * | | 类型 | 讲什么 | 重音 | 视觉暗示 |
 * |---|---|---|---|---|
 * | 🟢 | `内幕` | 拆解商业内幕／避坑指南（买房、中介话术） | 荧光黄 | 警示、内幕、打破常规 |
 * | 🔴 | `博弈` | 宏观经济／商业博弈／财富思维 | 琥珀金 ＋ 暗红光晕 | 资本、硬核博弈、危机 |
 * | 🔵 | `认知` | 职场交际／心理学／思维升级 | 极客青 ＋ 紫光斑 | 智慧、认知升级、理性 |
 *
 * ## ⚠ 经典红不当文案色
 *
 * 提案里类型二的文案色是「华尔街金／**经典红**」，红那一半没采纳，两个理由叠着：
 *
 * - **深蓝底 `#10263F` 上经典红 `#E5402C` 的对比度只有 3.72**，四舍五入连 4.5 都不到，
 *   是候选里最低的一个（白 15.32、荧光黄 10.70、极客青 9.27、琥珀金 8.22、科技紫 5.63）。
 *   这条线的验收标准是「缩到 210px 主标还读不读得出」—— 红是最先糊的那个。
 * - **红已经有活干了**：角标块和左侧色条。再拿它当重音就是一屏两个 accent，
 *   频道方案 §1.3 自己禁的（「两处以上强调等于没有强调」）。
 *
 * 所以红降级成**背景光晕**：不上字，只做危机氛围。科技紫同理（5.63），只做光斑不做字。
 *
 * ## ⚠ 为什么片子里的字幕标色也要跟着切
 *
 * 封面承诺一个重音色、片子里的关键数字标另一个色 —— 这个穿帮比封面和成片穿两件衬衫
 * 还明显，因为观众是**点进来的三秒内**做的对照。`build.mjs` 的 `标色` 因此默认跟着类型走。
 *
 * ## ⚠ 底色不切
 *
 * 提案里类型二可以走「深蓝/**暗灰**底」，暗灰没采纳 —— 底色一换，三种类型看着就像
 * 三个频道了。**底是 70% 那一半的东西**。真要暗灰，改这里的 `底` 就行，但先想清楚
 * 频道识别度那一头。
 */

