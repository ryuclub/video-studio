export const BEAT_NAMES = Object.keys(BEATS);

/** 取节拍。不认识的名字直接炸，别静默回退成常规——那会让一句设计过的话变平 */
export function getBeat(name: string | undefined): ShuoshuBeat {
  const key = name ?? '常规';
  const hit = BEATS[key];
  if (!hit) throw new Error(`没有这个节拍：${key}\n可用：${BEAT_NAMES.join(' / ')}`);
  return hit;
}
