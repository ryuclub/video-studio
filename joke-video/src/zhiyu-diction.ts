/**
 * ⚠ **引号里的算台词，外面的算旁白。**
 *
 * 这三条线的稿件**没有说话人标记** —— 全是段落，对白裹在引号里，所以只能这么分。
 * **判得出来的**：旁白里的语气词。
 * ⚠ **判不出来的**：不加引号的引述 —— 长片那条线撞过同一个坑
 * （「我问过他，你不累啊」那个「啊」是引述，排除不掉）。**所以那一项是 warn。**
 */
const 引号 = /[「"“][^」"”]*[」"”]/g;
const 去引述 = (s: string) => s.replace(引号, '');
const 取引述 = (s: string) => s.match(引号) ?? [];

const cn = (s: string) => [...s.replace(/\s/g, '')].length;

/**
 * **本期豁免**：`发布.json` 的 `用语豁免` 字段，值是**理由**。
 *
 * ⚠ **这不是给代码开的后门，是给存量稿开的。** 这份用语规范 2026-08-26 才立，
 * 而禅佛典 E01、心理 E01/E02、治愈那几期**都是在它之前写的、而且已经出片**。
 * 拿新规范去判旧稿，禅佛典 E01 一口气报 **64 个错** ——
 * **天天报错的闸门只会教人加 `--anyway`**，那样连有用的那几条也一起失效。
 *
 * 所以照 `zhiyu-check` 那个 `免问号` 的老办法：**豁免写在稿件自己的元信息里，
 * 带理由，而且体检每次都把它打出来**。不是代码替它免，是这一期自己声明的。
 *
 * ⚠ **豁免只降级不消音** —— error 变 warn，一条都不会被藏起来。
 */
export function 读用语豁免(projDir: string): string | null {
  try {
    const raw = readFileSync(`${projDir}/发布.json`, 'utf8');
    return (JSON.parse(raw) as { 用语豁免?: string }).用语豁免 ?? null;
  } catch {
    return null;
  }
}

export interface DictionIssue {
  level: 'error' | 'warn';
  rule: string;
  msg: string;
}

export interface DictionInput {
  /** 一条 line ＝ 一段。段名可选，用来在报错里定位 */
  text: string;
  section?: string;
  /** 这一段能不能豁免「无语气词」（比如清单体的落点句）。缺省不豁免 */
  allowTone?: boolean;
}

/**
 * 跑一遍 §十二 那八项。
 *
 * @param lines 稿件的段落（`⏸` 那种空行不要传进来）
 */
export function checkDiction(lines: DictionInput[], exempt?: string | null): DictionIssue[] {
  const raw: DictionIssue[] = [];
  const out = {
    push(i: DictionIssue) {
      // 豁免只降级不消音：error → warn，一条都不藏
      raw.push(exempt && i.level === 'error' ? { ...i, level: 'warn' as const, msg: `${i.msg}　〔本期豁免〕` } : i);
    },
    get length() { return raw.length; },
  };
  const at = (i: number, l: DictionInput) => `${l.section ? `【${l.section}】` : ''}第 ${i + 1} 段`;

  lines.forEach((l, i) => {
    const t = l.text;
    const n = cn(t);

    // ① 长度。**硬伤线是 error，20 字那条是 warn**
    if (n > LEN.hard)
      out.push({ level: 'error', rule: '超长句', msg: `${at(i, l)} ${n} 字，过了硬伤线 ${LEN.hard}（§5.1）：${t.slice(0, 24)}…` });
    else if (n > LEN.line)
      out.push({ level: 'warn', rule: '句长', msg: `${at(i, l)} ${n} 字，超过 ${LEN.line}（§5.1）。治愈线比说书线严四个字 —— 听众更困，句子更长就散了` });

    // ② 台词超长（引号里的）
    for (const q of 取引述(t)) {
      const m = cn(q.replace(/^[「"“]|[」"”]$/g, ''));
      if (m > LEN.quote)
        out.push({ level: 'warn', rule: '台词长度', msg: `${at(i, l)} 的台词 ${q.slice(0, 16)}… ${m} 字，超过 ${LEN.quote}（§5.1）` });
    }

    // ③ line 内标点 —— **一条 line 只承载一个信息点**（§5.3）
    //    ⚠ 句末那一个不算，中间出现才是该拆的信号
    const 中间标点 = t.slice(0, -1).match(/[。；]|——/g);
    if (中间标点)
      out.push({
        level: 'error',
        rule: '一句一件事',
        msg: `${at(i, l)} 句中出现「${中间标点.join('')}」—— **一条 line 只承载一个信息点，该拆**（§5.3）：${t.slice(0, 26)}…`,
      });

    // ④ 书面概念词 —— 在耳朵里是空的
    for (const w of 书面概念词)
      if (t.includes(w))
        out.push({ level: 'error', rule: '书面词', msg: `${at(i, l)} 有「${w}」—— **书面概念词黑名单**（§4.1）。这些词在文字里显得高级，在耳朵里是空的` });

    // ⑤ 第三层抽象词
    for (const w of 抽象词)
      if (t.includes(w))
        out.push({
          level: 'warn',
          rule: '抽象词',
          msg: `${at(i, l)} 有「${w}」（第三层：只能被判断出来的）—— **故事段／现象段一个都不许有**（§四）。提前说了等于剧透，后面的说破就没有落点`,
        });

    // ⑥ 高危字（同音歧义）
    const 命中 = 高危字.filter((c) => t.includes(c));
    if (命中.length >= 3)
      out.push({
        level: 'warn',
        rule: '高危字',
        msg: `${at(i, l)} 一段里有 ${命中.length} 个高危字（${命中.join('')}）—— 逐个念一遍（§2.1）：${t.slice(0, 22)}…`,
      });

    // ⑦ 旁白无语气词
    if (!l.allowTone) {
      const m = 去引述(t).match(语气词);
      if (m)
        out.push({
          level: 'warn',
          rule: '旁白语气',
          msg:
            `${at(i, l)} 旁白里有语气词「${m[0]}」（§七）。` +
            `⚠ **加引号的引述会排除，不加引号的排除不掉** —— 是不是误报要人看一眼`,
        });
    }

    // ⑩ 词边界：固定块被跨词凑出来（§二之二，2026-08-26 从说书线搬过来）
    //
    // 这一条跟 ⑥ 是**反方向**的：
    //   ⑥（§二）查「这个字**离开**它所在的词会不会变意」
    //   ⑩       查「这个字跟旁边的字**重新勾搭**成了另一个词」
    //
    // **在这条线上比在说书线更要紧。** 说书线的听众醒着、跟着情节，
    // 切分错了还能被情节拉回来；这条线的听众半睡，§〇 写着
    // 「一旦需要回想上一句，注意力就断了，而且往往不会再接回来」——
    // 词边界歧义正是「卡一下」的标准长相。
    for (const { re, why } of 词边界坑)
      if (re.test(t))
        out.push({ level: 'warn', rule: '词边界', msg: `${at(i, l)} 撞上词边界坑（§二之二）：${t.slice(0, 24)}…
      ${why}` });

    // ⑫ 书面腔（§8.2，2026-08-26 加）——**这四张表才是「太书面」的主体**
    for (const { w, to } of 书面虚词)
      if (t.includes(w))
        out.push({ level: 'warn', rule: '书面虚词', msg: `${at(i, l)} 有「${w}」（§8.2）→ ${to}　：${t.slice(0, 22)}…` });
    for (const { w, to, skip } of 双音动词)
      if (t.includes(w) && !(skip && skip.test(t)))
        out.push({ level: 'warn', rule: '双音动词', msg: `${at(i, l)} 有「${w}」—— 把动作说成了词（§8.2）→ ${to}　：${t.slice(0, 22)}…` });
    for (const w of 回指词)
      if (t.includes(w))
        out.push({ level: 'warn', rule: '回指词', msg: `${at(i, l)} 有「${w}」（§8.2）。**不是不许用，是用了就得把那个东西再说一遍** —— 听众看不见字，回头数就是卡一下` });
    {
      const m = 名词化.exec(t);
      if (m)
        out.push({ level: 'warn', rule: '名词化', msg: `${at(i, l)} 有「${m[0]}」—— 把动作说成了名词（§8.2）。**句子里没人在动了**，这是「机械化」最直接的来源` });
    }

    // ⑪ 现代词的额外坑（§2.2 那五行的机器实现，2026-08-26 补）
    for (const { re, why } of 现代词坑)
      if (re.test(t))
        out.push({ level: 'warn', rule: '现代词', msg: `${at(i, l)} 撞上现代词坑（§2.2）：${t.slice(0, 24)}…
      ${why}` });

    // ⑧ 判断句式的自我定义
    for (const re of 定义句式)
      if (re.test(t))
        out.push({ level: 'warn', rule: '认输句', msg: `${at(i, l)} 像在给自己下定义 —— **判断句改成认输句**（§8.3）：「我是不敢」→「我就是没敢试」` });
  });

  // ⑨ 长短交替：连续 5 句字数差 <3 就报（§5.2 全是等长句会催眠）
  for (let i = 0; i + 4 < lines.length; i++) {
    const w = lines.slice(i, i + 5).map((l) => cn(l.text));
    if (Math.max(...w) - Math.min(...w) < 3)
      out.push({
        level: 'warn',
        rule: '长短交替',
        msg: `${at(i, lines[i])} 起连续 5 段字数都在 ${Math.min(...w)}–${Math.max(...w)} 之间 —— **全是等长句会催眠，一段里至少一次明显落差**（§5.2）`,
      });
  }

  // ⑩ 指认型「你」。⚠ **脚本只统计并列出，指认／陪伴要人判**（§6.1）
  const 你 = lines
    .map((l, i) => ({ i, l, n: ([...l.text].filter((c) => c === '你')).length }))
    .filter((x) => x.n > 0);
  const 总 = 你.reduce((n, x) => n + x.n, 0);
  if (总 > 5)
    out.push({
      level: 'warn',
      rule: '你',
      msg:
        `全篇 ${总} 处「你」，落在 ${你.length} 段。**指认型 ≤5 次，陪伴型不限**（§6.1）—— ` +
        `脚本分不出这两种，**要人逐条判**：${你.slice(0, 4).map((x) => `${at(x.i, x.l)}`).join(' ')}${你.length > 4 ? ' …' : ''}`,
    });

  return fold(raw, Boolean(exempt));
}

/**
 * **同一条规则报了一堆，折成一行。**
 *
 * ⚠ **这不是把问题藏起来，是把「同一件事」说成一件事。**
 * 禅佛典 E01 第一版跑出来 **80 条提醒**，其中 60 条是「超长句」＋「一句一件事」——
 * 而那两条本来就是同一个病灶：**存量稿的段落粒度是「一段多句」，
 * 新规范要的是「一段一句」**。报 60 遍不会让人多明白一点，
 * **只会让人不看这份报告** —— 而不看的报告等于没有闸。
 *
 * 折叠之后一行说清：哪条规则、几处、前两处在哪。要逐条看就去看稿子。
 */
function fold(issues: DictionIssue[], exempt: boolean): DictionIssue[] {
  const 阈 = exempt ? 3 : 8; // 豁免期折得更狠：那些本来就不打算改
  /** 只取「【段名】第 N 段」那一截，别把整条消息再抄一遍 */
  const 位置 = (m: string) => (m.match(/^(?:【[^】]*】)?第 \d+ 段/) ?? ['?'])[0];
  const by = new Map<string, DictionIssue[]>();
  for (const x of issues) by.set(x.rule, [...(by.get(x.rule) ?? []), x]);
  const out: DictionIssue[] = [];
  for (const [rule, list] of by) {
    if (list.length < 阈) {
      out.push(...list);
      continue;
    }
    // 折叠版只留：几处 · 规则本身在说什么 · 前三处在哪
    const 说明 = list[0].msg
      .replace(/^(?:【[^】]*】)?第 \d+ 段 ?/, '')
      .replace(/[:：].*$/, '')
      .replace(/　〔本期豁免〕$/, '')
      .trim();
    out.push({
      level: list.some((x) => x.level === 'error') ? 'error' : 'warn',
      rule,
      msg:
        `**${list.length} 处**　${说明}` +
        `　→ ${list.slice(0, 3).map((x) => 位置(x.msg)).join('　')}${list.length > 3 ? ' …' : ''}` +
        (exempt ? '　〔本期豁免〕' : ''),
    });
  }
  return out;
}



