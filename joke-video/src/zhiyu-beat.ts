// ── 治愈档节拍表：一共三个节拍，这个数字是故意的 ──────────────────────
//
// 说书那张（shuoshu-beat.ts）有 12 个节拍：悬、扣子、揭底、贴近、点评……
// 每个都在调 delivery 和 gain，因为说书要**演**，而且「15 分钟全程一个音量
// 一个语速」在那条线上是失败。
//
// **治愈档反过来：单调就是目标。** 主讲员设定的文本闸写得很直白 ——
// 感叹号全删、问句改陈述、形容词减一半、不写数字堆砌。文本层面就已经
// 把起伏拿掉了，音频层面再加起伏是自相矛盾。所以这张表：
//
//   · **不动 delivery**（全季一条音色，见方案文档第二节）
//   · **不动 gain**（深夜档任何一次音量抬升都是一次「睁眼」的机会）
//   · 只剩下停顿长度这一个变量
//
// 三个节拍分别对应稿件里的三级结构：段落 / ⏸ / 幕。**不要往这张表里加东西。**
// 要哪一句特别一点，先问「文本闸是不是能解决」——十次有九次能。
//
// ── 数值的来历：全是听出来的，不是规范里抄的 ──
//
// 选题稿件给治愈档写的是「句间 0.8–1.2s、段间 2.5–3.5s、硬切 4.0s」，
// 理由是垫了 −62dBFS 房间底噪之后，长停顿才不像卡带
// （TTS 插的是绝对静音，实测 −227dB）。
//
// **底噪那一层确实成立**（v1 干声在停顿处实测 −61.5dB，是房间声不是死寂），
// **但长停顿照样被否了**。《方丈记》幕一试听三轮：
//
//   v1  段间 1.25 / ⏸ 3.0　→「⏸ 处停得太久」
//   v2  段间 0.6  / ⏸ 1.6　→「太紧」（收过头 —— 挨批的本来只有 ⏸ 那一级）
//   v3  段间 1.25 / ⏸ 1.6　→ **定稿**
//
// 说书线当年也从 1.2–2.2s 一路压到 1.0 以内，反馈同样是「停多了」。
// 同一堵墙撞了两次：**底噪解决的是停顿的「质地」，不是「长度」。**
// 谁要按稿件那组数字重设这张表，先去听 listen/v1/ 里那条。
//
// 过程和实测见 projects/治愈/2026-08-19_hojoki/listen/说明.md，
// 结论写进了 zhiyu/治愈系出片方案.md 第一节。

export interface ZhiyuBeat {
  /** 这一段之后留白（秒） */
  pause: number;
  desc: string;
}

export const BEATS: Record<string, ZhiyuBeat> = {
  /** 默认。段与段之间，稿件里绝大多数换行都是这个，标注时不用写 */
  常规: { pause: 1.25, desc: '段与段之间' },

  /**
   * 稿件里标 ⏸ 的地方。每 3–4 分钟一个，一期 6–7 个。
   * 作用是「这一节说完了」——**收口，不是悬念**。
   * 前一句必须是收得住的句子，不能停在半截意思上（幕表的硬要求）。
   */
  停顿点: { pause: 1.6, desc: '一节说完，换气' },

  /**
   * 幕与幕之间。一期两幕，所以**每期只出现一次**。
   *
   * 2.2s 是 v3 试听里备选那条的 ⏸ 值 —— 是听过的数，不是估的，
   * 但**没有单独验过它当幕间用**。这是全表唯一一个不是从定稿版直接来的值，
   * 下一轮试听（幕一 + 幕二 连听）顺带验掉。
   */
  幕末: { pause: 2.2, desc: '一幕讲完，换一幕' },
};

export const BEAT_NAMES = Object.keys(BEATS);

/** 取节拍。不认识的名字直接炸，别静默回退成常规 */
export function getBeat(name: string | undefined): ZhiyuBeat {
  const key = name ?? '常规';
  const hit = BEATS[key];
  if (!hit) throw new Error(`没有这个节拍：${key}\n可用：${BEAT_NAMES.join(' / ')}`);
  return hit;
}
