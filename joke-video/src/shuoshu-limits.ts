// ── 说书线的稿件级阈值：一处定义，稿件闸和体检共用 ──────────────────
//
// **为什么单开一个文件。** 这些数原来只长在 `shuoshu-preflight.ts` 里，
// 而体检要 `script.json` —— 也就是解析（②）和标注（③）都做完之后才跑得动。
// 于是「字数够不够」这种**纯稿件属性**要等到下游才暴露，而补稿又正好会打乱
// 标注和场景表：稿子出问题 → 改稿 → 冲掉两样已经做完的东西。这是个环。
//
// 2026-08-26 加了 `shuoshu-lint.ts`，直接读 markdown、跑在解析之前。
// 两道闸必须用**同一套数**。抄一份过去就是这仓库反复吃亏的那种「两处各算一套」——
// 迟早出现「稿件闸说够了、体检说短了」，而那种不一致没人核得出是哪边错的
// （`出片手册` §一之二 里排期表抽成 `upcoming()` 是同一个理由）。

/**
 * 实测语速，汉字每分钟（含停顿）。
 *
 * E01 228 / E02 237 / E03 230 / E04 234 / E05 239 / **E06 235**。
 *
 * ⚠ **228 是这六期里最慢的一档，对旁白多的一期偏保守。**
 * E05（旁白 90%）实测 239，E06（旁白 89%）实测 235 —— 按 228 估都会多算一分多钟，
 * 于是 24 分钟那条上限被误报。**知道这件事，别把警告当真错。**
 * 要更准就得按旁白占比取值，但那要 script.json（解析之后），
 * 而这套数的用处恰恰是在解析之前 —— 所以留在这儿，保守一点。
 */
export const CPM = 228;

/** 现行下限。低于这个是**错**，出片会被拦住 */
export const TARGET_MIN = 18;

/**
 * 老标准（15–17 分钟）的下限。**在这之间只警告不拦。**
 *
 * E01（16.8 分）和 E02（15.9 分）是按老标准做的，不该被新标准倒查成错 ——
 * 已经出过的片子不回改，这是这个仓库的一贯做法。
 * 但也不能一声不吭：哪天要重出，得知道它们按今天的标准是偏短的。
 */
export const LEGACY_MIN = 15;

/** 上限。长不是错，但要确认不是车轱辘话 */
export const TARGET_MAX = 24;

/**
 * 分幕汉字下限。卡片里每一幕后面括号那个数就是这个，**是下限不是配额**。
 * 这里给的是通用兜底值，各篇卡片上的数更准 —— 但卡片在文档里，机器读不到，
 * 所以先用一套保守的通用值拦住「明显塌了」的那种。
 */
export const ACT_FLOOR: Record<string, number> = {
  冷开场: 150,
  引入: 300,
  '幕X · ': 400,
  收束: 300,
};

/** 幕末那一段最多几个汉字。规范：每幕结尾一个短句独立成段 */
export const ACT_TAIL_MAX = 30;

/**
 * **只数汉字，不含标点。**
 *
 * E03 第一版就是在这儿栽的：估字数时把标点算进去，写着「约 3300 字」，
 * 实际只有 1969 汉字 —— 高估了三成，成片 8:38。
 */
export const han = (t: string): number => (t.match(/[一-龥]/g) ?? []).length;

/** 这一幕的字数下限。`幕一 · 背判官` 这类一律按「幕X」那一档 */
export const actFloor = (act: string): number =>
  (/^幕/.test(act) ? ACT_FLOOR['幕X · '] : ACT_FLOOR[act]) ?? 0;
